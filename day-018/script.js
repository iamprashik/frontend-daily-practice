const score = 85;

if (score >= 90) {
    console.log(`Score: ${score} - Grade: A`);
} else if (score >= 80) {
    console.log(`Score: ${score} - Grade: B`);
} else if (score >= 70) {
    console.log(`Score: ${score} - Grade: C`);
} else if (score >= 60) {
    console.log(`Score: ${score} - Grade: D`);
} else {
    console.log(`Score: ${score} - Grade: F`);
}