// String - represents text
const name = "Prashik";

// Number - represents numeric values
const age = 23;

// Boolean - represents true or false
const isLearning = true;

// Undefined - a variable without an assigned value
let currentProject;

// Null - represents an intentionally empty value
const emptyValue = null;

// BigInt - represents very large integers
const largeNumber = 12345678901234567890n;

// Symbol - represents a unique value
const uniqueId = Symbol("id");

console.log("Name:", name);
console.log("Age:", age);
console.log("Learning JavaScript:", isLearning);
console.log("Current project:", currentProject);
console.log("Empty value:", emptyValue);
console.log("Large number:", largeNumber);
console.log("Unique ID:", uniqueId);

// Checking data types
console.log(typeof name);
console.log(typeof age);
console.log(typeof isLearning);