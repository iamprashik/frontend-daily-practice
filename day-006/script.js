const a = 10;
const b = 5;

// Greater than
console.log("10 > 5:", a > b);

// Less than
console.log("10 < 5:", a < b);

// Greater than or equal
console.log("10 >= 10:", a >= 10);

// Less than or equal
console.log("5 <= 10:", b <= a);

// Equal value
console.log("10 == '10':", a == "10");

// Equal value and type
console.log("10 === '10':", a === "10");

// Not equal
console.log("10 != 5:", a != b);

// Strictly not equal
console.log("10 !== '10':", a !== "10");