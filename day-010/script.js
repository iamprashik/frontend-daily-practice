const language = "JavaScript";

// Convert to uppercase
const uppercaseLanguage = language.toUpperCase();

console.log("Original:", language);
console.log("Uppercase:", uppercaseLanguage);

// Convert to lowercase
const lowercaseLanguage = language.toLowerCase();

console.log("Lowercase:", lowercaseLanguage);

// Another example
const name = "Prashik";

console.log(`Original name: ${name}`);
console.log(`Uppercase name: ${name.toUpperCase()}`);
console.log(`Lowercase name: ${name.toLowerCase()}`);

// The original string does not change
console.log("Original value is still:", language);