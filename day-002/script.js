
// const is used for a value that does not change
const name = "Prashik";
const learningGoal = "Become a better frontend developer";

// let is used for a value that can change
let completedDays = 1;

console.log("Name:", name);
console.log("Goal:", learningGoal);
console.log("Completed days:", completedDays);

// Updating a let variable
completedDays = completedDays + 1;

console.log("Updated completed days:", completedDays);