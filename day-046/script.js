// Day 046 - Introduction to Arrays

// Store multiple values in one array
const favoriteArtists = [
    "Beirut",
    "Radiohead",
    "Coldplay",
    "The Strokes"
];

// Print the entire array
console.log("Favorite artists:", favoriteArtists);

// Access individual elements
console.log("First artist:", favoriteArtists[0]);
console.log("Second artist:", favoriteArtists[1]);
console.log("Third artist:", favoriteArtists[2]);

// Count the elements
console.log("Number of artists:", favoriteArtists.length);
